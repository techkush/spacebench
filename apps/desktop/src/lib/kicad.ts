// KiCad symbol library access. The build script (scripts/build-kicad-symbols.mjs)
// converts the official KiCad libraries (CC-BY-SA 4.0 + design exception) into
// gzipped JSON under /kicad. Libraries load on demand and resolved symbols are
// cached so the editor can render synchronously.

export interface KPin {
  /** pin number */
  n: string
  name: string
  /** connection point, grid units, Y down */
  x: number
  y: number
  /** direction from the connection point towards the body (0 = +x, 90 = up, 180 = -x, 270 = down) */
  a: number
  /** electrical type: input, output, passive, power_in, … */
  t: string
  /** hidden pin */
  h?: 1
}
export interface KUnit {
  name?: string
  svg: string
  pins: KPin[]
  /** px box: x, y, w, h */
  box: [number, number, number, number]
}
export interface KField { v: string; x?: number; y?: number; r?: number; h?: 1; j?: string }
interface RawDef {
  extends?: string
  desc?: string
  ds?: string
  fp?: string
  fpf?: string
  fields: { Reference?: KField; Value?: KField }
  sim?: Record<string, string>
  nosim?: 1
  power?: 1
  units?: KUnit[]
}

export interface SymbolDef {
  /** "Lib:Name" */
  id: string
  lib: string
  name: string
  /** names up the `extends` chain, nearest first (e.g. ["NE555D"]) */
  bases: string[]
  desc: string
  datasheet?: string
  /** default KiCad footprint ("Package_TO_SOT_THT:TO-92_Inline") and footprint filters */
  footprint?: string
  footprintFilters?: string[]
  refPrefix: string
  value: string
  power: boolean
  units: KUnit[]
  fields: { Reference?: KField; Value?: KField }
  sim?: Record<string, string>
  excludeFromSim: boolean
}

export interface IndexRow {
  lib: string; name: string; desc: string; keywords: string; ref: string; units: number; power: boolean
  /** has a working simulation model (from sim-index.json, generated by `pnpm kicad:sim-index`) */
  sim: boolean
}

// ---------------------------------------------------------------- loading

type Loader = (file: string) => Promise<unknown>

async function fetchGz(file: string): Promise<unknown> {
  const res = await fetch(`/kicad/${file}.gz`)
  if (!res.ok) throw new Error(`Could not load ${file} (${res.status})`)
  // dev servers may already have decoded it (Content-Encoding: gzip); check the magic bytes
  const bytes = new Uint8Array(await res.arrayBuffer())
  const gz = bytes[0] === 0x1f && bytes[1] === 0x8b
  const text = gz ? await new Response(new Blob([bytes]).stream().pipeThrough(new DecompressionStream("gzip"))).text() : new TextDecoder().decode(bytes)
  return JSON.parse(text)
}

let loader: Loader = fetchGz
/** Tests swap in a filesystem loader. */
export function setLoader(l: Loader) { loader = l }

const libs = new Map<string, Promise<Record<string, RawDef>>>()
const raw = new Map<string, Record<string, RawDef>>()
const cache = new Map<string, SymbolDef>()
const builtins = new Map<string, SymbolDef>()

function loadLib(lib: string): Promise<Record<string, RawDef>> {
  let p = libs.get(lib)
  if (!p) {
    p = (loader(`lib/${lib}.json`) as Promise<Record<string, RawDef>>).then((d) => { raw.set(lib, d); return d })
    libs.set(lib, p)
    p.catch(() => libs.delete(lib))
  }
  return p
}

let indexP: Promise<IndexRow[]> | null = null
/**
 * Every KiCad symbol (the full database is always kept). Rows carry `sim`: whether the
 * part simulates today; the UI hides the others but they stay available for later
 * (model import, MCU co-simulation…).
 */
export function loadIndex(): Promise<IndexRow[]> {
  indexP ??= Promise.all([
    loader("index.json") as Promise<{ rows: [string, string, string, string, string, number, number][] }>,
    (loader("sim-index.json") as Promise<Record<string, string[]>>).catch(() => null),
  ]).then(([d, simIndex]) => {
    const simSet = simIndex ? new Set(Object.entries(simIndex).flatMap(([lib, names]) => names.map((n) => `${lib}:${n}`))) : null
    return d.rows.map(([lib, name, desc, keywords, ref, units, power]) => ({
      lib, name, desc, keywords, ref, units, power: !!power, sim: simSet ? simSet.has(`${lib}:${name}`) : true,
    }))
  })
  return indexP
}

/** Parts the UI offers: simulation-ready ones unless `all` (the hidden rest stays in the database). */
export const visibleRows = (rows: IndexRow[], all = false) => (all ? rows : rows.filter((r) => r.sim))

function resolve(lib: string, name: string): SymbolDef | undefined {
  const d = raw.get(lib)?.[name]
  if (!d) return undefined
  const chain: RawDef[] = [d]
  const bases: string[] = []
  let cur = d
  while (cur.extends && raw.get(lib)?.[cur.extends] && bases.length < 8) {
    bases.push(cur.extends)
    cur = raw.get(lib)![cur.extends]
    chain.push(cur)
  }
  const root = chain[chain.length - 1]
  const pick = <K extends keyof RawDef>(k: K) => chain.find((c) => c[k] !== undefined)?.[k]
  const fields = { Reference: pick("fields")?.Reference, Value: d.fields.Value ?? root.fields.Value }
  // derived symbols may override field positions individually
  for (const c of chain) {
    fields.Reference ??= c.fields.Reference
    fields.Value ??= c.fields.Value
  }
  const sim = Object.assign({}, ...[...chain].reverse().map((c) => c.sim ?? {})) as Record<string, string>
  return {
    id: `${lib}:${name}`,
    lib,
    name,
    bases,
    desc: d.desc ?? pick("desc") ?? "",
    datasheet: d.ds ?? pick("ds"),
    footprint: d.fp ?? pick("fp"),
    footprintFilters: (d.fpf ?? pick("fpf"))?.split(/\s+/).filter(Boolean),
    refPrefix: (fields.Reference?.v ?? "U").replace(/\?$/, ""),
    value: fields.Value?.v ?? name,
    power: !!root.power,
    units: root.units ?? [],
    fields,
    sim: Object.keys(sim).length ? sim : undefined,
    excludeFromSim: !!pick("nosim"),
  }
}

/** Synchronous lookup — undefined until `ensureSymbols` has loaded the library. */
export function getSymbol(id: string): SymbolDef | undefined {
  const b = builtins.get(id)
  if (b) return b
  let s = cache.get(id)
  if (s) return s
  const i = id.indexOf(":")
  s = resolve(id.slice(0, i), id.slice(i + 1))
  if (s) cache.set(id, s)
  return s
}

export async function ensureSymbols(ids: Iterable<string>): Promise<void> {
  const need = new Set<string>()
  for (const id of ids) if (!builtins.has(id) && !getSymbol(id)) need.add(id.slice(0, id.indexOf(":")))
  await Promise.all([...need].map(loadLib))
}

export async function loadSymbol(id: string): Promise<SymbolDef> {
  await ensureSymbols([id])
  const s = getSymbol(id)
  if (!s) throw new Error(`Symbol ${id} not found in the KiCad library`)
  return s
}

export function registerBuiltin(def: SymbolDef) { builtins.set(def.id, def) }

