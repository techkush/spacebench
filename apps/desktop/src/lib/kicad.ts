/** Search the index: every word must match name, description, keywords or library. */
export function searchIndex(rows: IndexRow[], q: string, limit = 300): IndexRow[] {
  const words = q.toLowerCase().split(/\s+/).filter(Boolean)
  if (!words.length) return []
  const out: { r: IndexRow; s: number }[] = []
  for (const r of rows) {
    const name = r.name.toLowerCase()
    const hay = `${name} ${r.desc.toLowerCase()} ${r.keywords.toLowerCase()} ${r.lib.toLowerCase()}`
    if (!words.every((w) => hay.includes(w))) continue
    const w0 = words[0]
    const s = name === w0 ? 0 : name.startsWith(w0) ? 1 : name.includes(w0) ? 2 : 3
    out.push({ r, s: s * 1000 + Math.min(name.length, 999) })
  }
  out.sort((a, b) => a.s - b.s)
  return out.slice(0, limit).map((o) => o.r)
}

/** KiCad-style unit letter: 1 → A, 2 → B … */
export const unitLetter = (u: number) => String.fromCharCode(64 + u)
